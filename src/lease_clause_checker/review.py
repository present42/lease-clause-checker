"""Render the test set as a Markdown table, so people can review the labels without the JSONL.

Render only clauses that `check_clauses` has passed: the table presents each quote as the
decisive words of the cached section.
"""

import re
from collections import Counter
from pathlib import PurePath

from lease_clause_checker.clauses import Clause
from lease_clause_checker.elaws import NOTICE, CachedAct

KIND_NAMES = {"clear": "clear", "near_miss": "near-miss"}
# Characters Markdown (including GitHub's `$` maths) could read as formatting.
MARKDOWN_SPECIAL = re.compile(r"([\\`*_\[\]<>|$~&])")


def render_review(
    clauses: list[Clause], clauses_path: PurePath, clauses_sha256: str, act: CachedAct
) -> str:
    labels = Counter(clause.label for clause in clauses)
    kinds = Counter(clause.kind for clause in clauses)
    by_section = Counter(clause.section for clause in clauses)
    reviewed = sum(clause.reviewed for clause in clauses)
    lines = [
        "# Test-set labels for review",
        "",
        f"Generated by `uv run lcc clauses review` from `{clauses_path.as_posix()}` "
        f"(SHA-256 `{clauses_sha256}`); edit that file, not this one. The clauses are invented. "
        "Labels and rationales are not legal advice.",
        "",
        f"Statute quotes are from the cached Act: {act.consolidation} Retrieved "
        f"{act.retrieved_at:%Y-%m-%d}, content SHA-256 `{act.content_sha256}`. {NOTICE}",
        "",
        f"{len(clauses)} clauses: {labels['void']} void, {labels['allowed']} allowed; "
        f"{kinds['clear']} clear, {kinds['near_miss']} near-miss. "
        f"Reviewed: {reviewed} of {len(clauses)}.",
        "",
        "By section: "
        + ", ".join(
            f"s. {number} ({count})"
            for number, count in sorted(by_section.items(), key=lambda item: _sort_key(item[0]))
        )
        + ".",
        "",
        "| id | kind | label | section | clause | rationale | decisive words of the section |",
        "|---|---|---|---|---|---|---|",
    ]
    lines += [
        "| "
        + " | ".join(
            (
                _escape(clause.id),
                KIND_NAMES[clause.kind],
                f"**{clause.label}**",
                _section_cell(clause),
                _escape(clause.text),
                _escape(clause.rationale),
                f"“{_escape(clause.quote)}”",
            )
        )
        + " |"
        for clause in clauses
    ]
    return "\n".join(lines) + "\n"


def _section_cell(clause: Clause) -> str:
    cell = f"[s. {clause.section}]({clause.source})"
    if clause.also_accept:
        cell += " (also " + ", ".join(f"s. {other}" for other in clause.also_accept) + ")"
    return cell


def _escape(value: str) -> str:
    return MARKDOWN_SPECIAL.sub(r"\\\1", value)


def _sort_key(section_number: str) -> tuple[int, ...]:
    return tuple(int(part) for part in section_number.split("."))
