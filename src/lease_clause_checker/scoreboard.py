def score_set(
    clauses: list[Clause],
    clauses_sha256: str,
    results_dir: Path,
    prompts: tuple[baseline.Prompt, pipeline.PipelinePrompt],
    sections: dict[str, Section],
) -> ScoredSet:
    """Every model's saved answers on `clauses`, by both methods."""
    baseline_prompt, pipeline_prompt = prompts
    store = Store(results_dir, pipeline_prompt.version, clauses_sha256)
    runs: dict[tuple[Method, str], ModelRun] = {}
    for spec in MODELS:
        runs["baseline", spec.key] = baseline_run(
            results_dir, baseline_prompt, spec, clauses, clauses_sha256, sections
        )
        runs["pipeline", spec.key] = pipeline_run(store, pipeline_prompt, spec, clauses, sections)
    return ScoredSet(clauses, runs)


def restrict(run: ModelRun, clauses: Sequence[Clause]) -> ModelRun:
    """`run` limited to `clauses`, matched by id and text."""
    texts = {clause.id: clause.text for clause in clauses}
    scores = [s for s in run.scores if texts.get(s.clause.id) == s.clause.text]
    ids = {s.clause.id for s in scores}
    records = [r for r in run.records if r.clause_id in ids]
    return ModelRun(run.spec, records, scores, [r for r in run.results if r.clause.id in ids])


def render(board: Board, chart_link: str) -> str:
    """The README block, markers included."""
    if len(board.selection.scores) != len(board.stress.clauses):
        raise ReportDataError("the selection run doesn't cover every stress-set clause")
    parts = [
        START,
        _collected(board),
        _headline(board.main),
        _main_table(board.main, chart_link),
        _light_right_heavy_wrong(board.main),
        _stress_table(board),
        _gallery(board),
        _notes(board),
        END,
    ]
    return "\n\n".join(parts) + "\n"


def replace_block(readme: str, block: str) -> str:
    start, end = readme.find(START), readme.find(END)
    if start < 0 or end < start:
        raise MissingMarkersError(f"no {START!r} … {END!r} block to replace")
    return readme[:start] + block.rstrip("\n") + readme[end + len(END) :]


def _one(items: Iterable[T], what: str) -> T:
    found = list(items)
    if len(found) != 1:
        raise ReportDataError(f"expected one {what}, found {len(found)}")
    return found[0]


def _spec(key: str) -> ModelSpec:
    return _one((s for s in MODELS if s.key == key), f"model {key}")


def _normalise(text: str) -> str:
    return " ".join(text.split())


def _pairs() -> list[tuple[ModelSpec, ModelSpec]]:
    """(light, heavy) per provider, in MODELS order."""
    return [
        (
            light,
            _one(
                (s for s in MODELS if s.provider == light.provider and s.weight == "heavy"),
                f"heavy {light.provider} model",
            ),
        )
        for light in MODELS
        if light.weight == "light"
    ]


def _verdict_right(score: Score) -> bool:
    return score.outcome == "correct"


def _exact(score: Score) -> bool:
    return score.section_result == "deciding"


def _section_ok(score: Score) -> bool:
    return score.section_result in ("deciding", "also_accepted")


def _all_right(score: Score) -> bool:
    return _verdict_right(score) and _section_ok(score)


def _hits(run: ModelRun, clauses: list[Clause], test: Callable[[Score], bool]) -> list[bool]:
    by_id = {score.clause.id: score for score in run.scores}
    return [test(by_id[clause.id]) for clause in clauses]


def _count(hits: list[bool]) -> str:
    low, high = count_interval(hits)
    interval = "see Notes" if low == high else f"{low}{DASH}{high}"
    return f"{sum(hits)} of {len(hits)} ({interval})"


def _signed(value: int) -> str:
    return f"{value:+d}".replace("-", MINUS) if value else "0"


def _cost(run: ModelRun) -> str:
    return f"${run.cost_usd:.2f}" if run.cost_usd >= 0.10 else f"${run.cost_usd:.3f}"


def _collected(board: Board) -> str:
    days = sorted(
        {
            record.requested_at.date()
            for scored in (board.main, board.stress)
            for run in scored.runs.values()
            for record in run.records
        }
        | {record.requested_at.date() for record in board.selection.records}
    )
    if not days:
        return "No answers are saved yet."
    return f"Answers collected {_day_span(days[0], days[-1])} (UTC)."


def _day_span(first: date, last: date) -> str:
    if first == last:
        return f"{first.day} {first:%B %Y}"
    if (first.year, first.month) == (last.year, last.month):
        return f"{first.day}{DASH}{last.day} {last:%B %Y}"
    return f"{first.day} {first:%B %Y} to {last.day} {last:%B %Y}"


def _headline(scored: ScoredSet) -> str:
    n = len(scored.clauses)
    lines = [
        "### Headline: a light model with the pipeline vs a heavy model alone",
        "",
        f"Main test set, {n} clauses. In brackets: {PERCENT} bootstrap intervals over clauses "
        f"({RESAMPLES:,} resamples, fixed seed); for the difference, a paired bootstrap.",
        "",
        f"| | verdicts right | exact deciding section | cost for the {n} clauses |",
        "|---|---|---|---|",
    ]
    for light, heavy in _pairs():
        light_name = f"{light.name} + pipeline (light)"
        heavy_name = f"{heavy.name} alone (heavy)"
        missing = scored.missing("pipeline", light) or scored.missing("baseline", heavy)
        if missing:
            lines.append(f"| {light_name} vs {heavy_name} | {missing} | | |")
            continue
        light_run, heavy_run = scored.run("pipeline", light), scored.run("baseline", heavy)
        cells = {}
        for name, test in (("verdict", _verdict_right), ("exact", _exact)):
            a = _hits(light_run, scored.clauses, test)
            b = _hits(heavy_run, scored.clauses, test)
            low, high = difference_interval(a, b)
            interval = "see Notes" if low == high else f"{_signed(low)} to {_signed(high)}"
            cells[name] = (_count(a), _count(b), f"{_signed(sum(a) - sum(b))} ({interval})")
        unsure = sum(s.outcome == "unsure" for s in light_run.scores)
        light_verdicts = cells["verdict"][0] + (f"; {unsure} unsure" if unsure else "")
        light_verdicts += _no_answer(light_run)
        heavy_verdicts = cells["verdict"][1] + _no_answer(heavy_run)
        lines += [
            f"| {light_name} | {light_verdicts} | {cells['exact'][0]} | {_cost(light_run)} |",
            f"| {heavy_name} | {heavy_verdicts} | {cells['exact'][1]} | {_cost(heavy_run)} |",
            f"| difference | {cells['verdict'][2]} | {cells['exact'][2]} | |",
        ]
    lines += [
        "",
        f"A difference counts only if its interval excludes 0; a gap of 1{DASH}2 clauses is not "
        "called a difference.",
    ]
    lines += _without_contested(scored)
    return "\n".join(lines)


def _without_contested(scored: ScoredSet) -> list[str]:
    """The headline counts again without the clauses whose labels are contested."""
    contested = [c.id for c in scored.clauses if c.id in _contested_ids()]
    if not contested:
        return []
    kept = [c for c in scored.clauses if c.id not in contested]
    parts = []
    for light, heavy in _pairs():
        if scored.missing("pipeline", light) or scored.missing("baseline", heavy):
            continue
        for name, run in (
            (f"{light.name} + pipeline", scored.run("pipeline", light)),
            (f"{heavy.name} alone", scored.run("baseline", heavy)),
        ):
            verdicts = sum(_hits(run, kept, _verdict_right))
            exact = sum(_hits(run, kept, _exact))
            parts.append(f"{name} {verdicts} and {exact}")
    if not parts:
        return []
    return [
        "",
        f"Without the contested clauses ({', '.join(contested)}; see Notes), {len(kept)} "
        f"clauses, verdicts right and exact sections: {'; '.join(parts)}.",
    ]


def _contested_ids() -> set[str]:
    return {item.clause_id for item in CONTESTED_LABELS}


def _main_table(scored: ScoredSet, chart_link: str) -> str:
    n = len(scored.clauses)
    void = sum(c.label == "void" for c in scored.clauses)
    lines = [
        "### Every model and method on the main set",
        "",
        f"{n} clauses: {void} void, {n - void} allowed.",
        "",
        "| model | method | verdicts right | false alarms | missed voids | unsure "
        "| quote verified | section ok | exact section | cost |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for spec in MODELS:
        for method in METHODS:
            name = f"{spec.name} ({spec.weight})"
            missing = scored.missing(method, spec)
            if missing:
                lines.append(f"| {name} | {method} | {missing} | | | | | | | |")
                continue
            run = scored.run(method, spec)
            outcomes = [s.outcome for s in run.scores]
            pipeline_only = method == "pipeline"
            lines.append(
                f"| {name} | {method} "
                f"| {_count(_hits(run, scored.clauses, _verdict_right))}{_no_answer(run)} "
                f"| {outcomes.count('false_alarm')} of {n - void} "
                f"| {outcomes.count('missed_void')} of {void} "
                f"| {outcomes.count('unsure') if pipeline_only else DASH} "
                f"| {f'{_quotes_verified(run)} of {n}' if pipeline_only else DASH} "
                f"| {sum(_hits(run, scored.clauses, _section_ok))} of {n} "
                f"| {_count(_hits(run, scored.clauses, _exact))} "
                f"| {_cost(run)} |"
            )
    lines += [
        "",
        "- **false alarms**: lawful clauses called void. **missed voids**: void clauses "
        "called lawful.",
        "- **quote verified**: the final answer's quote passed the check, so the cited section "
        "exists and contains the quote. The baseline gives no quote to check.",
        "- **section ok** counts the deciding section or an accepted alternative (s. 4 for "
        "every void clause, for example); **exact section** counts the deciding section only.",
        "- **cost**: list prices on the day of each call, retries included. The Gemini calls "
        "went through Vertex AI but are priced at the Gemini API's list prices (see "
        "[results/README.md](results/README.md)).",
        "",
        f"![Verdicts right and exact deciding section, per model and method, with {PERCENT} "
        f"bootstrap intervals]({chart_link})",
    ]
    return "\n".join(lines)


def _quotes_verified(run: ModelRun) -> int:
    return sum(_final_verified(result) for result in run.results)


def _final_verified(result: Result) -> bool:
    return not result.gave_up and result.attempts[-1].check == "verified"


def _light_right_heavy_wrong(scored: ScoredSet) -> str:
    """Clauses where a light model has the verdict and an accepted section and its heavy
    sibling (same method) does not."""
    found, ids = [], set()
    for light, heavy in _pairs():
        for method in METHODS:
            if scored.missing(method, light) or scored.missing(method, heavy):
                continue
            light_by_id = {s.clause.id: s for s in scored.run(method, light).scores}
            for heavy_score in scored.run(method, heavy).scores:
                light_score = light_by_id[heavy_score.clause.id]
                if _all_right(light_score) and not _all_right(heavy_score):
                    ids.add(heavy_score.clause.id)
                    found.append(
                        f"{heavy_score.clause.id} ({method}: {heavy.name} "
                        f"{_citation(heavy_score.answer)}; {light.name} "
                        f"{_citation(light_score.answer)})"
                    )
    listing = "; ".join(found) if found else "none"
    contested = sorted(ids & _contested_ids())
    see_note = f" On {', '.join(contested)}, see the note on contested labels." if contested else ""
    return (
        "Main-set clauses where a light model had the verdict and an accepted section and its "
        f"heavy sibling, by the same method, did not: {listing}.{see_note}"
    )


def _no_answer(run: ModelRun) -> str:
    """ "; k gave no verdict" for answers with no readable verdict (see the output-cap note),
    so the verdict columns visibly add up."""
    missing = sum(s.answer.verdict is None for s in run.scores)
    return f"; {missing} gave no verdict" if missing else ""


def _citation(answer: Answer) -> str:
    if answer.verdict is None and answer.section is None:
        return "gave no answer"
    if answer.section is None:
        return "cited no section"
    return f"cited s. {answer.section}"


def _stress_table(board: Board) -> str:
    scored = board.stress
    n = len(scored.clauses)
    chooser = board.selection.spec.name
    lines = [
        "### Stress set",
        "",
        f"{n} clauses **chosen because {chooser}'s baseline answer got them wrong** "
        "(see [data/README.md](data/README.md)), so they are not a sample of anything and "
        f"{chooser}'s baseline score here is low by design. They were chosen on baseline "
        "failures only, so the set favours the pipeline. They are reported apart from the "
        "main set. The selection run is the answer each clause was chosen on; the fresh run "
        "asked again after the set was frozen. A break is a wrong verdict, or a right verdict "
        "with a section that isn't accepted; the two are counted separately.",
        "",
        "| model | method | run | wrong verdict | unsure | right verdict, wrong section "
        "| all right | cost |",
        "|---|---|---|---|---|---|---|---|",
        _stress_row(board.selection, "baseline", "selection", n),
    ]
    for spec in MODELS:
        for method in METHODS:
            missing = scored.missing(method, spec)
            if missing:
                lines.append(f"| {spec.name} ({spec.weight}) | {method} | {missing} | | | | | |")
            else:
                lines.append(_stress_row(scored.run(method, spec), method, "fresh", n))
    return "\n".join(lines)


def _stress_row(run: ModelRun, method: Method, label: str, n: int) -> str:
    wrong = sum(s.outcome in ("false_alarm", "missed_void", "no_verdict") for s in run.scores)
    unsure = sum(s.outcome == "unsure" for s in run.scores)
    section_only = sum(_verdict_right(s) and not _section_ok(s) for s in run.scores)
    right = sum(_all_right(s) for s in run.scores)
    return (
        f"| {run.spec.name} ({run.spec.weight}) | {method} | {label} | {wrong} of {n} "
        f"| {unsure if method == 'pipeline' else DASH} | {section_only} of {n} "
        f"| {right} of {n} | {_cost(run)} |"
    )


def _gallery(board: Board) -> str:
    clauses = {clause.id: clause for clause in board.main.clauses}
    lines = [
        "### Failure gallery",
        "",
        "Real baseline answers from the main set, quoted from the saved records, then the "
        "pipeline's one retry.",
    ]
    for exhibit in GALLERY:
        clause = clauses[exhibit.clause_id]
        spec = _spec(exhibit.model_key)
        run = board.main.run("baseline", spec)
        where = f"{spec.key} {clause.id}"
        record = _one((r for r in run.records if r.clause_id == clause.id), f"answer {where}")
        score = _one((s for s in run.scores if s.clause.id == clause.id), f"score {where}")
        if _all_right(score):
            raise ReportDataError(f"{where}: a gallery answer must be wrong")
        for excerpt in exhibit.excerpts:
            if _normalise(excerpt) not in _normalise(record.text):
                raise ReportDataError(f"{where}: not in the answer: {excerpt!r}")
        quoted = "\n>\n".join(f"> …{excerpt}…" for excerpt in exhibit.excerpts)
        lines += [
            "",
            f"**{clause.id}, {spec.name}, baseline.** Clause: “{clause.text}” Label: "
            f"{clause.label} (s. {clause.section}).",
            "",
            quoted,
            "",
            exhibit.comment,
        ]
    lines += ["", _retry_exhibit(board)]
    return "\n".join(lines)


def _retry_exhibit(board: Board) -> str:
    model_key, clause_id = RETRY_EXHIBIT
    spec = _spec(model_key)
    where = f"{model_key} {clause_id}"
    runs = board.main.run("pipeline", spec).results
    result = _one((r for r in runs if r.clause.id == clause_id), f"pipeline result {where}")
    if len(result.attempts) != 2:
        raise ReportDataError(f"{where}: the retry exhibit needs two attempts")
    first, retry = result.attempts
    if first.answer is None or retry.answer is None:
        raise ReportDataError(f"{where}: an attempt in the retry exhibit is unreadable")
    right_first = (first.answer.verdict, first.answer.cited_section) == (
        result.clause.label,
        result.clause.section,
    )
    as_described = _normalise(retry.answer.quote.replace(RETRY_DROPPED, "")) == _normalise(
        first.answer.quote
    )
    if not (right_first and as_described and retry.check == "verified"):
        raise ReportDataError(f"{where}: the retry is not as described")
    return "\n".join(
        [
            f"**{clause_id}, {spec.name}, pipeline: the retry.** The first answer had the "
            "right verdict and section, but its quote failed the check "
            f"({(first.check or 'unreadable').replace('_', ' ')}):",
            "",
            f"> {first.answer.quote}",
            "",
            f"It is s. {result.clause.section}(2) with “{RETRY_DROPPED.strip()}” cut from the "
            "middle and no mark where the words were dropped. The model was told "
            f"“{first.problem()}” and asked again; the second quote (verified) was the "
            "subsection in full:",
            "",
            f"> {retry.answer.quote}",
        ]
    )


def _notes(board: Board) -> str:
    n = len(board.main.clauses)
    lines = [
        "### Notes",
        "",
        f"- **Perfect scores.** A bootstrap of {n} of {n} only ever redraws right answers, so "
        f'its interval would be {n}{DASH}{n}; the tables say "see Notes" instead. By the '
        f"exact (Clopper{DASH}Pearson) two-sided {PERCENT} interval, {n} of {n} is still "
        f"consistent with an error rate of up to {perfect_score_error_bound(n):.1%}.",
    ]
    lines += _thinking_note(board.main)
    lines += _output_cap_note(board)
    lines += _contested_labels_note(board.main)
    lines += _late_fee_note(board.stress)
    lines += [
        f"- {spec.name} was run first and dropped as a top-tier model; records kept."
        for spec in DROPPED_MODELS
    ]
    lines.append(
        "- Statute words quoted above: Source: Ontario e-Laws. Not an official version of the "
        "statute. © King's Printer for Ontario, 2006."
    )
    return "\n".join(lines)


def _thinking_note(scored: ScoredSet) -> list[str]:
    """Median billed output tokens per main-set baseline answer, and Gemini's thinking share."""
    parts, silent = [], []
    for spec in MODELS:
        if scored.missing("baseline", spec):
            continue
        records = scored.run("baseline", spec).records
        part = f"{spec.name} {statistics.median(r.output_tokens for r in records):,.0f}"
        if spec.provider == "google":
            thinking = [_thinking_tokens(r.raw) for r in records]
            part += f" (thinking {statistics.median(thinking):,.0f})"
            if not any(thinking):
                silent.append(spec.name)
        parts.append(part)
    if not parts:
        return []
    line = (
        "- **Thinking.** Every model runs at its provider's default thinking setting (for "
        "Claude, effort medium). Median billed output tokens per main-set baseline answer, "
        f"thinking included (Gemini reports its thinking share): {'; '.join(parts)}."
    )
    for name in silent:
        line += f" At its default, {name} did not think on any main-set baseline answer."
    return [line]


def _thinking_tokens(raw: dict[str, Any]) -> int:
    usage = raw.get("usage_metadata") or {}
    return int(usage.get("thoughts_token_count") or 0)


def _output_cap_note(board: Board) -> list[str]:
    """Every scored answer the output-token cap stopped, by set, model and method. For the
    pipeline only the final attempt counts: a capped first attempt that was retried is not
    the answer scored."""
    groups = []
    for set_name, scored in (("main set", board.main), ("stress set", board.stress)):
        for (method, key), run in scored.runs.items():
            final = (
                [result.attempts[-1].record for result in run.results]
                if method == "pipeline"
                else run.records
            )
            capped = sorted(r.clause_id for r in final if r.finish_reason in OUTPUT_CAP_REASONS)
            if capped:
                groups.append(f"{_spec(key).name}, {method}, {set_name}: {', '.join(capped)}")
    if not groups:
        return []
    return [
        f"- **Output cap.** These answers stopped at the {MAX_OUTPUT_TOKENS:,}-token output "
        "cap, which thinking counts against, and are scored as they stand: "
        f"{'; '.join(sorted(groups))}. A baseline answer cut off before its verdict counts as "
        "a wrong verdict; a pipeline answer cut off counts as unsure."
    ]


def _contested_labels_note(scored: ScoredSet) -> list[str]:
    by_id = {c.id: c for c in scored.clauses}
    present = [item for item in CONTESTED_LABELS if item.clause_id in by_id]
    if not present:
        return []
    ids = " and ".join(item.clause_id for item in present)
    lines = [
        f"- **Contested labels.** Answers argue against the frozen labels of {ids}. They are "
        "scored as frozen, since the labels were fixed before any model saw the set; the "
        f"answers are read in full in [verdict-misses.md]({VERDICT_MISSES})."
    ]
    for item in present:
        clause = by_id[item.clause_id]
        scores = [
            (f"{_spec(key).name} ({method})", s)
            for (method, key), run in scored.runs.items()
            for s in run.scores
            if s.clause.id == item.clause_id
        ]
        wrong = sorted(name for name, s in scores if s.outcome in WRONG_VERDICTS)
        accepted = "".join(f", with s. {other} also accepted" for other in clause.also_accept)
        label = "lawful" if clause.label == "allowed" else "void"
        line = (
            f"  - **{clause.id}** (“{clause.text}”) is labelled {label} under s. "
            f"{clause.section}{accepted}. {_argued(item, scored)} Wrong verdict in the tables: "
            f"{', '.join(wrong) or 'none'}."
        )
        cited = item.unaccepted_section
        if cited is not None:
            if cited in (clause.section, *clause.also_accept):
                raise ReportDataError(f"{clause.id} now accepts s. {cited}; update the note")
            citing = sorted(name for name, s in scores if s.answer.section == cited)
            line += (
                f" Also, {item.why_cited}, but a citation of s. {cited} counts as a wrong "
                f"section. Cited s. {cited}: {', '.join(citing) or 'none'}."
            )
        lines.append(line)
    return lines


def _argued(item: ContestedLabel, scored: ScoredSet) -> str:
    """ "<Model>'s baseline answer argued that …", checked against each saved answer."""
    names = []
    for key, excerpt in item.argued_by:
        spec = _spec(key)
        where = f"contested label {item.clause_id}, {spec.name}"
        if scored.missing("baseline", spec):
            raise ReportDataError(f"{where}: baseline {scored.missing('baseline', spec)}")
        run = scored.run("baseline", spec)
        score = _one((s for s in run.scores if s.clause.id == item.clause_id), where)
        if score.outcome not in WRONG_VERDICTS:
            raise ReportDataError(f"{where}: the baseline verdict is not wrong")
        record = _one((r for r in run.records if r.clause_id == item.clause_id), where)
        if _normalise(excerpt) not in _normalise(record.text):
            raise ReportDataError(f"{where}: not in the answer: {excerpt!r}")
        names.append(f"{spec.name}'s")
    answers = "answers" if len(names) > 1 else "answer"
    return f"{' and '.join(names)} baseline {answers} argued {item.argument}."


def _late_fee_note(scored: ScoredSet) -> list[str]:
    clause_id, section = LATE_FEE_NOTE
    clause = next((c for c in scored.clauses if c.id == clause_id), None)
    if clause is None:
        return []
    if clause.section != section:
        raise ReportDataError(f"{clause_id} is no longer decided by s. {section}")
    return [
        f"- **{clause_id}** (stress set: “{clause.text}”) is decided by s. {section}'s “a "
        "specific sum becomes due upon a default of the tenant in paying rent due”, "
        "independently of O. Reg. 516/06, which as far as we know permits charges for "
        "bounced (NSF) payments but not late fees."
    ]


def render_chart(scored: ScoredSet) -> str:
    """An SVG dot plot: verdicts right and exact deciding section, per model and method."""
    n = len(scored.clauses)
    panels = (("Verdicts right", _verdict_right), ("Exact deciding section", _exact))
    label_w, panel_w, gap, top, row_h = 150, 260, 40, 70, 44
    width = label_w + 2 * panel_w + gap + 20
    plot_bottom = top + row_h * len(MODELS)
    height = plot_bottom + 52
    title = f"Main test set, {n} clauses: counts with {PERCENT} bootstrap intervals"
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" aria-labelledby="title desc" '
        'font-family="system-ui, sans-serif" font-size="12">',
        f'<title id="title">{title}</title>',
        '<desc id="desc">For each model, the number of clauses with the right verdict and with '
        "the exact deciding section, by the baseline (circles) and the pipeline (diamonds). "
        "The README's tables give the same numbers.</desc>",
        "<style>",
        ".bg{fill:#fcfcfb}.t1{fill:#0b0b0b}.t2{fill:#52514e}.grid{stroke:#e4e3df}"
        ".baseline{fill:#2a78d6;stroke:#2a78d6}.pipeline{fill:#eb6834;stroke:#eb6834}"
        ".ring{stroke:#fcfcfb}",
        "@media (prefers-color-scheme: dark){.bg{fill:#1a1a19}.t1{fill:#f0efec}"
        ".t2{fill:#c3c2b7}.grid{stroke:#3a3a38}.baseline{fill:#3987e5;stroke:#3987e5}"
        ".pipeline{fill:#d95926;stroke:#d95926}.ring{stroke:#1a1a19}}",
        "</style>",
        f'<rect class="bg" width="{width}" height="{height}"/>',
        f'<text class="t1" x="4" y="18" font-size="14" font-weight="600">{title}</text>',
        _legend_item(4, 40, "baseline", "baseline (plain question)"),
        _legend_item(204, 40, "pipeline", "pipeline (Act in prompt, checked quote)"),
    ]
    for p, (panel_title, test) in enumerate(panels):
        x0 = label_w + p * (panel_w + gap)

        def x(count: int, x0: int = x0) -> float:
            return x0 + panel_w * count / n

        out += [
            f'<text class="t1" x="{x0}" y="{top - 8}" font-weight="600">{panel_title}</text>',
            f'<text class="t2" x="{x0 + panel_w / 2:.1f}" y="{plot_bottom + 34}" '
            f'text-anchor="middle">clauses, of {n}</text>',
        ]
        for tick in sorted({0, 10, 20, 30, n}):
            out += [
                f'<line class="grid" x1="{x(tick):.1f}" x2="{x(tick):.1f}" y1="{top}" '
                f'y2="{plot_bottom}"/>',
                f'<text class="t2" x="{x(tick):.1f}" y="{plot_bottom + 16}" '
                f'text-anchor="middle">{tick}</text>',
            ]
        for r, spec in enumerate(MODELS):
            y_mid = top + row_h * r + row_h / 2
            if p == 0:
                out.append(f'<text class="t1" x="4" y="{y_mid + 4:.1f}">{spec.name}</text>')
            for m, method in enumerate(METHODS):
                y = y_mid + (m - 0.5) * 14
                missing = scored.missing(method, spec)
                if missing:
                    out.append(
                        f'<text class="t2" x="{x0}" y="{y + 4:.1f}">{method}: {missing}</text>'
                    )
                    continue
                hits = _hits(scored.run(method, spec), scored.clauses, test)
                low, high = count_interval(hits)
                tip = html.escape(f"{spec.name}, {method}: {sum(hits)} of {n} ({low}{DASH}{high})")
                out += [
                    f"<g><title>{tip}</title>",
                    f'<line class="{method}" x1="{x(low):.1f}" x2="{x(high):.1f}" '
                    f'y1="{y:.1f}" y2="{y:.1f}" stroke-width="2"/>',
                    _marker(method, x(sum(hits)), y),
                    "</g>",
                ]
    out.append("</svg>")
    return "\n".join(out) + "\n"


def _marker(method: Method, x: float, y: float) -> str:
    """A circle for the baseline, a diamond for the pipeline: shape as well as colour."""
    if method == "baseline":
        return (
            f'<circle class="{method} ring" cx="{x:.1f}" cy="{y:.1f}" r="5" stroke-width="2" '
            'paint-order="stroke"/>'
        )
    points = f"{x:.1f},{y - 6:.1f} {x + 6:.1f},{y:.1f} {x:.1f},{y + 6:.1f} {x - 6:.1f},{y:.1f}"
    return (
        f'<polygon class="{method} ring" points="{points}" stroke-width="2" paint-order="stroke"/>'
    )


def _legend_item(x: int, y: int, method: Method, label: str) -> str:
    return f'{_marker(method, x + 6, y - 4)}<text class="t2" x="{x + 18}" y="{y}">{label}</text>'
