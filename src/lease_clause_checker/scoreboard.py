def score_set(
    clauses: list[Clause],
    clauses_sha256: str,
    results_dir: Path,
    prompts: tuple[baseline.Prompt, pipeline.PipelinePrompt],
    sections: dict[str, Section],
) -> ScoredSet:
    """Every model's saved answers on `clauses`, by both methods."""
    baseline_prompt, pipeline_prompt = prompts
    store = Store(results_dir, pipeline_prompt.version, clauses_sha256)
    runs: dict[tuple[Method, str], ModelRun] = {}
    for spec in MODELS:
        runs["baseline", spec.key] = baseline_run(
            results_dir, baseline_prompt, spec, clauses, clauses_sha256, sections
        )
        runs["pipeline", spec.key] = pipeline_run(store, pipeline_prompt, spec, clauses, sections)
    return ScoredSet(clauses, runs)


def restrict(run: ModelRun, clauses: Sequence[Clause]) -> ModelRun:
    """`run` limited to `clauses`, matched by id and text."""
    texts = {clause.id: clause.text for clause in clauses}
    scores = [s for s in run.scores if texts.get(s.clause.id) == s.clause.text]
    ids = {s.clause.id for s in scores}
    records = [r for r in run.records if r.clause_id in ids]
    return ModelRun(run.spec, records, scores, [r for r in run.results if r.clause.id in ids])


def render(board: Board, chart_link: str) -> str:
    """The README block, markers included."""
    if len(board.selection.scores) != len(board.stress.clauses):
        raise ReportDataError("the selection run doesn't cover every stress-set clause")
    parts = [
        START,
        _collected(board),
        _headline(board.main),
        _main_table(board.main, chart_link),
        _light_right_heavy_wrong(board.main),
        _stress_table(board),
        _closed_book_table(board),
        _gallery(board),
        _notes(board),
        END,
    ]
    return "\n\n".join(parts) + "\n"


def replace_block(readme: str, block: str, start_marker: str = START, end_marker: str = END) -> str:
    start, end = readme.find(start_marker), readme.find(end_marker)
    if start < 0 or end < start:
        raise MissingMarkersError(f"no {start_marker!r} … {end_marker!r} block to replace")
    return readme[:start] + block.rstrip("\n") + readme[end + len(end_marker) :]


def render_tldr(board: Board) -> str:
    """The README's TL;DR block, markers included: six lines, each from the saved answers."""
    by_provider = {light.provider: (light, heavy) for light, heavy in _pairs()}
    lines = [
        _tldr_closed_book_quotes(board),
        _tldr_checked_citations(board),
        _tldr_headline(board.main, *by_provider["anthropic"]),
        _tldr_statute_not_check(board, by_provider["anthropic"][0]),
        _tldr_right_section(board.main),
        _tldr_thinking_cost(board.main, *by_provider["google"]),
    ]
    return "\n".join([TLDR_START, "**TL;DR**", "", *(f"- {line}" for line in lines), TLDR_END])


def _pipeline_results(board: Board) -> list[tuple[Result, Score]]:
    """Every model's pipeline results on the main and stress sets, each with its score."""
    pairs: list[tuple[Result, Score]] = []
    for scored in (board.main, board.stress):
        for spec in MODELS:
            if scored.missing("pipeline", spec):
                raise ReportDataError(
                    f"TL;DR: {spec.name} pipeline {scored.missing('pipeline', spec)}"
                )
            run = scored.run("pipeline", spec)
            pairs += zip(run.results, run.scores, strict=True)
    return pairs


def _tldr_closed_book_quotes(board: Board) -> str:
    """The models that got every closed-book verdict right yet had quotes that failed the
    word-for-word check, and how many; then the pipeline's first quotes, with the statute in the
    prompt. A model whose quotes all passed is left out."""
    n = len(board.main.clauses)
    perfect = [
        run
        for run in _closed_book_runs(board)
        if sum(_hits(run, board.main.clauses, _verdict_right)) == n
    ]
    failed = {
        run.spec.name: count
        for run in perfect
        if (count := sum(r.attempt.check != "verified" for r in run.closed_book))
    }
    minor = [
        sum(
            r.quote is not None and r.quote.category in ("cosmetic", "conventions")
            for r in run.closed_book
        )
        for run in perfect
        if run.spec.name in failed
    ]
    if not failed:
        raise ReportDataError("TL;DR: no closed-book run has right verdicts and failed quotes")
    for spec in MODELS:
        if board.main.missing("pipeline", spec):
            raise ReportDataError(
                f"TL;DR: {spec.name} pipeline {board.main.missing('pipeline', spec)}"
            )
    verified, checked = _first_pipeline_checks(board)
    names, counts = _and_list(list(failed)), _and_list([str(c) for c in failed.values()])
    if len(failed) == 1:
        (count,) = failed.values()
        quotes = f"{count} of its {n} quotes failed the word-for-word check"
    else:
        quotes = f"{counts} of their {n} quotes, respectively, failed the word-for-word check"
    if any(minor):
        quotes += (
            f" ({_and_list([str(m) for m in minor])} of them differing only cosmetically or by "
            "quoting conventions)"
        )
    return (
        f"Closed book (no statute text in the prompt), {names} got all {n} verdicts right, yet "
        f"{quotes}. With the statute in "
        f"the prompt, {verified} of {checked} first pipeline answers with a verdict on the main "
        f"set, from the {len(MODELS)} models, had a quote that passed."
    )


def _closed_book_runs(board: Board) -> list[ModelRun]:
    """Every model's closed-book run on the main set, in MODELS order; each must be complete."""
    runs = []
    for spec in MODELS:
        run = board.closed_book.get(spec.key)
        if run is None or len(run.scores) != len(board.main.clauses):
            raise ReportDataError(f"TL;DR: {spec.name}'s closed-book run is not complete")
        runs.append(run)
    return runs


def _stops_early_line(board: Board, closed_book: list[ModelRun]) -> str:
    """How many passing quotes `verify.ending` flags as stopping early: every model's first
    pipeline answer on the main set, and the closed-book answers."""
    pipeline_first = [
        result.attempts[0] for spec in MODELS for result in board.main.run("pipeline", spec).results
    ]
    closed = [result.attempt for run in closed_book for result in run.closed_book]
    (p_early, p_passed), (c_early, c_passed) = (
        _stops_early(attempts, board.sections) for attempts in (pipeline_first, closed)
    )
    return (
        "- A quote that passes the word-for-word check can still stop before the list item "
        "that decides the clause. A rough rule in code (`verify.ending`, shown as a warning by "
        f"the MCP tools) flags {p_early} of the {p_passed} passing first pipeline quotes and "
        f"{c_early} of the {c_passed} passing closed-book quotes as possibly stopping early. "
        "These are upper limits, not counts: the rule flags every passing quote with a list "
        "item after it, including quotes that already hold the item that applies. They have "
        "not yet been checked by hand."
    )


def _stops_early(
    attempts: Iterable[pipeline.Attempt], sections: dict[str, Section]
) -> tuple[int, int]:
    """(flagged as stopping early, passed) over the attempts whose quote passed."""
    passed = [a.answer for a in attempts if a.check == "verified" and a.answer is not None]
    endings = [verify.ending(answer.quote, answer.cited_section, sections) for answer in passed]
    early = sum(e is not None and e.completeness == "stops_early" for e in endings)
    return early, len(passed)


def _first_pipeline_checks(board: Board) -> tuple[int, int]:
    """(verified, checked) over every model's first pipeline answer with a verdict on the main
    set."""
    first = [
        result.attempts[0]
        for spec in MODELS
        for result in board.main.run("pipeline", spec).results
        if result.attempts[0].check is not None
    ]
    return sum(attempt.check == "verified" for attempt in first), len(first)


def _tldr_checked_citations(board: Board) -> str:
    pairs = _pipeline_results(board)
    verified = [score for result, score in pairs if _final_verified(result)]
    gave_up = sum(result.gave_up for result, _ in pairs)
    own_unsure = sum(r.answer.verdict == "unsure" and not r.gave_up for r, _ in pairs)
    unaccepted = sum(not _section_ok(score) for score in verified)
    clauses = len(board.main.clauses) + len(board.stress.clauses)
    rest = []
    if own_unsure:
        rest.append(f"{own_unsure} {_was(own_unsure)} the model's own `unsure`")
    if gave_up:
        rest.append(f"{gave_up} {_was(gave_up)} `unsure` after two failed quotes")
    return (
        "Every pipeline verdict comes with a citation a reader can check: a section of the Act "
        "and a quote from it that code has checked word for word (`lcc check` adds a link to "
        "the section on e-Laws). If the quote fails twice, the answer is `unsure`, not an "
        f"unchecked citation. Of {len(pairs)} pipeline answers ({len(MODELS)} models, "
        f"{clauses} clauses), {len(verified)} had a checked quote"
        f"{''.join(f'; {part}' for part in rest)}. A checked quote shows the words are in the "
        f"Act, not that the section decides the clause: {unaccepted} of the {len(verified)} "
        "cited a section the label doesn't accept."
    )


def _was(count: int) -> str:
    return "was" if count == 1 else "were"


def _tldr_headline(scored: ScoredSet, light: ModelSpec, heavy: ModelSpec) -> str:
    n = len(scored.clauses)
    light_run, heavy_run = scored.run("pipeline", light), scored.run("baseline", heavy)
    light_right = sum(_hits(light_run, scored.clauses, _verdict_right))
    heavy_right = sum(_hits(heavy_run, scored.clauses, _verdict_right))
    tie = f" {n} clauses can't tell them apart." if light_right == heavy_right else ""
    return (
        f"On the {n}-clause main set (synthetic clauses; the pipeline is given the text of "
        f"the rule sections), {light.name} with the pipeline got {light_right} of {n} "
        f"verdicts right for {_cost(light_run)}; {heavy.name} alone got {heavy_right} of {n} "
        f"for {_cost(heavy_run)}.{tie}"
    )


def _tldr_statute_not_check(board: Board, light: ModelSpec) -> str:
    """What moved the light model's verdicts: the statute text (closed book vs pipeline), and
    how little the quote check did."""
    n = len(board.main.clauses)
    closed = _one((r for r in _closed_book_runs(board) if r.spec == light), light.name)
    closed_right = sum(_hits(closed, board.main.clauses, _verdict_right))
    with_text = sum(_hits(board.main.run("pipeline", light), board.main.clauses, _verdict_right))
    if closed_right >= with_text:
        raise ReportDataError("TL;DR: the statute text no longer explains the verdicts")
    results = [result for result, _ in _pipeline_results(board)]
    checked = [r for r in results if r.attempts[0].check is not None]
    failed = [r for r in checked if r.attempts[0].check != "verified"]
    changed = sum(
        r.attempts[0].answer is not None and r.attempts[0].answer.verdict != r.answer.verdict
        for r in failed
    )
    line = (
        f"For {light.name}, the statute text moved the verdicts, not the quote check: closed "
        f"book, it got {closed_right} of {n} verdicts right; with the text, {with_text}. The check "
        f"failed {len(failed)} of {len(checked)} checked first answers"
    )
    model_key, clause_id = RETRY_EXHIBIT
    if len(failed) == 1 and (failed[0].clause.id, failed[0].attempts[0].record.model_key) == (
        clause_id,
        model_key,
    ):
        _retry_exhibit(board)  # checks the description below
        line += (
            f" ({clause_id}: {_spec(model_key).name} dropped words from the middle of "
            f"s. {failed[0].clause.section}(2))"
        )
    if changed:
        return (
            f"{line}, and the retry changed {changed} {'verdict' if changed == 1 else 'verdicts'}."
        )
    return f"{line}, and the retry changed no verdict."


def _tldr_right_section(scored: ScoredSet) -> str:
    """The baseline's own words: it is asked whether a clause is "enforceable"."""
    model_key, clause_id, what = RIGHT_SECTION_WRONG_VERDICT
    spec = _spec(model_key)
    where = f"TL;DR {model_key} {clause_id}"
    score = _one(
        (s for s in scored.run("baseline", spec).scores if s.clause.id == clause_id), where
    )
    wrong = score.outcome in ("false_alarm", "missed_void")
    if score.section_result != "deciding" or not wrong:
        raise ReportDataError(f"{where}: not a right section with a wrong verdict")
    called = "enforceable" if score.answer.verdict == "allowed" else "not enforceable"
    return (
        f"A right section is not a right answer: on {clause_id}, {spec.name}'s baseline cited "
        f"s. {score.clause.section}, {what}, and still called the clause {called}."
    )


def _tldr_thinking_cost(scored: ScoredSet, light: ModelSpec, heavy: ModelSpec) -> str:
    runs = {
        (method, spec.key): scored.run(method, spec)
        for method in METHODS
        for spec in (light, heavy)
    }
    dearer = all(runs[m, light.key].cost_usd > runs[m, heavy.key].cost_usd for m in METHODS)
    if not dearer or any(_thinking_tokens(r.raw) for r in runs["baseline", heavy.key].records):
        raise ReportDataError("TL;DR: the thinking-cost line no longer holds")
    light_pipeline = runs["pipeline", light.key]
    thinking_usd = sum(
        light.cost_usd(0, _thinking_tokens(r.raw), r.requested_at.date())
        for r in light_pipeline.records
    )
    share = thinking_usd / light_pipeline.cost_usd
    by_method = "; ".join(
        f"{m} {_cost(runs[m, light.key])} vs {_cost(runs[m, heavy.key])}" for m in METHODS
    )
    return (
        f"Cost followed each model's default thinking setting, not its tier: {light.name} with "
        f"the pipeline cost {_cost(light_pipeline)} on the main set, {share:.0%} of it for "
        f"thinking tokens, and {heavy.name} alone {_cost(runs['baseline', heavy.key])}. By the "
        f"same method, too, {light.name} cost more ({by_method}); at its default, "
        f"{heavy.name} did not think on any baseline answer."
    )


def _one(items: Iterable[T], what: str) -> T:
    found = list(items)
    if len(found) != 1:
        raise ReportDataError(f"expected one {what}, found {len(found)}")
    return found[0]


def _and_list(items: Sequence[str]) -> str:
    """ "a", "a and b", "a, b and c"."""
    if len(items) < 3:
        return " and ".join(items)
    return f"{', '.join(items[:-1])} and {items[-1]}"


def _spec(key: str) -> ModelSpec:
    return _one((s for s in MODELS if s.key == key), f"model {key}")


def _normalise(text: str) -> str:
    return " ".join(text.split())


def _pairs() -> list[tuple[ModelSpec, ModelSpec]]:
    """(light, heavy) per provider, in MODELS order."""
    return [
        (
            light,
            _one(
                (s for s in MODELS if s.provider == light.provider and s.weight == "heavy"),
                f"heavy {light.provider} model",
            ),
        )
        for light in MODELS
        if light.weight == "light"
    ]


def _verdict_right(score: Score) -> bool:
    return score.outcome == "correct"


def _exact(score: Score) -> bool:
    return score.section_result == "deciding"


def _section_ok(score: Score) -> bool:
    return score.section_result in ("deciding", "also_accepted")


def _all_right(score: Score) -> bool:
    return _verdict_right(score) and _section_ok(score)


def _hits(run: ModelRun, clauses: list[Clause], test: Callable[[Score], bool]) -> list[bool]:
    by_id = {score.clause.id: score for score in run.scores}
    return [test(by_id[clause.id]) for clause in clauses]


def _count(hits: list[bool]) -> str:
    low, high = count_interval(hits)
    interval = "see Notes" if low == high else f"{low}{DASH}{high}"
    return f"{sum(hits)} of {len(hits)} ({interval})"


def _signed(value: int) -> str:
    return f"{value:+d}".replace("-", MINUS) if value else "0"


def _cost(run: ModelRun) -> str:
    return f"${run.cost_usd:.2f}" if run.cost_usd >= 0.10 else f"${run.cost_usd:.3f}"


def _collected(board: Board) -> str:
    days = sorted(
        {
            record.requested_at.date()
            for scored in (board.main, board.stress)
            for run in scored.runs.values()
            for record in run.records
        }
        | {record.requested_at.date() for record in board.selection.records}
    )
    if not days:
        return "No answers are saved yet."
    return f"Answers collected {_day_span(days[0], days[-1])} (UTC)."


def _day_span(first: date, last: date) -> str:
    if first == last:
        return f"{first.day} {first:%B %Y}"
    if (first.year, first.month) == (last.year, last.month):
        return f"{first.day}{DASH}{last.day} {last:%B %Y}"
    return f"{first.day} {first:%B %Y} to {last.day} {last:%B %Y}"


def _headline(scored: ScoredSet) -> str:
    n = len(scored.clauses)
    lines = [
        "### Headline: a light model with the pipeline vs a heavy model alone",
        "",
        f"Main test set, {n} clauses. In brackets: {PERCENT} bootstrap intervals over clauses "
        f"({RESAMPLES:,} resamples, fixed seed); for the difference, a paired bootstrap.",
        "",
        f"| | verdicts right | exact deciding section | cost for the {n} clauses |",
        "|---|---|---|---|",
    ]
    for light, heavy in _pairs():
        light_name = f"{light.name} + pipeline (light)"
        heavy_name = f"{heavy.name} alone (heavy)"
        missing = scored.missing("pipeline", light) or scored.missing("baseline", heavy)
        if missing:
            lines.append(f"| {light_name} vs {heavy_name} | {missing} | | |")
            continue
        light_run, heavy_run = scored.run("pipeline", light), scored.run("baseline", heavy)
        cells = {}
        for name, test in (("verdict", _verdict_right), ("exact", _exact)):
            a = _hits(light_run, scored.clauses, test)
            b = _hits(heavy_run, scored.clauses, test)
            low, high = difference_interval(a, b)
            interval = "see Notes" if low == high else f"{_signed(low)} to {_signed(high)}"
            cells[name] = (_count(a), _count(b), f"{_signed(sum(a) - sum(b))} ({interval})")
        unsure = sum(s.outcome == "unsure" for s in light_run.scores)
        light_verdicts = cells["verdict"][0] + (f"; {unsure} unsure" if unsure else "")
        light_verdicts += _no_answer(light_run)
        heavy_verdicts = cells["verdict"][1] + _no_answer(heavy_run)
        lines += [
            f"| {light_name} | {light_verdicts} | {cells['exact'][0]} | {_cost(light_run)} |",
            f"| {heavy_name} | {heavy_verdicts} | {cells['exact'][1]} | {_cost(heavy_run)} |",
            f"| difference | {cells['verdict'][2]} | {cells['exact'][2]} | |",
        ]
    lines += [
        "",
        f"A difference counts only if its interval excludes 0; a gap of 1{DASH}2 clauses is not "
        "called a difference.",
    ]
    lines += _without_contested(scored)
    return "\n".join(lines)


def _without_contested(scored: ScoredSet) -> list[str]:
    """The headline counts again without the clauses whose labels are contested."""
    contested = [c.id for c in scored.clauses if c.id in _contested_ids()]
    if not contested:
        return []
    kept = [c for c in scored.clauses if c.id not in contested]
    parts, covered = [], []
    for light, heavy in _pairs():
        if scored.missing("pipeline", light) or scored.missing("baseline", heavy):
            continue
        for name, run in (
            (f"{light.name} + pipeline", scored.run("pipeline", light)),
            (f"{heavy.name} alone", scored.run("baseline", heavy)),
        ):
            verdicts = sum(_hits(run, kept, _verdict_right))
            exact = sum(_hits(run, kept, _exact))
            parts.append(f"{name} {verdicts} and {exact}")
            misses = {s.clause.id for s in run.scores if not _verdict_right(s)}
            if misses and misses <= set(contested):
                covered.append(f"{name} ({_and_list(sorted(misses))})")
    if not parts:
        return []
    line = (
        f"Without the contested clauses ({_and_list(contested)}; see Notes), {len(kept)} "
        f"clauses, verdicts right and exact sections: {'; '.join(parts)}."
    )
    if covered:
        counts = "that count is" if len(covered) == 1 else "those counts are"
        line += (
            f" The contested clauses are the only ones that {_and_list(covered)} got wrong or "
            f"were unsure on, so {counts} perfect by construction."
        )
    return ["", line]


def _contested_ids() -> set[str]:
    return {item.clause_id for item in CONTESTED_LABELS}


