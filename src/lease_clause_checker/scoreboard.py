@dataclass(frozen=True)
class ScoredSet:
    clauses: list[Clause]
    runs: dict[tuple[Method, str], ModelRun]
    """By method and model key; a model with no saved answers has a run with no scores."""

    def run(self, method: Method, spec: ModelSpec) -> ModelRun:
        return self.runs[method, spec.key]

    def missing(self, method: Method, spec: ModelSpec) -> str | None:
        """None if every clause has a scored answer; else what to show instead of numbers."""
        answered = len(self.run(method, spec).scores)
        if answered == len(self.clauses):
            return None
        if answered == 0:
            return "not run yet"
        return f"partial: {answered} of {len(self.clauses)} answered"


@dataclass(frozen=True)
class Board:
    main: ScoredSet
    stress: ScoredSet
    selection: ModelRun
    """The selection run's baseline answers on the stress-set clauses."""
    closed_book: dict[str, ModelRun] = field(default_factory=dict)
    """The closed-book run on the main set, by model key; a model not run is left out."""
    quote_checks: quotereview.HandChecks = field(default_factory=dict)
    """The hand checks of the closed-book quotes that are not word for word."""
    hand_check_record: handcheck.Record | None = None
    """How the closed-book quotes' hand checks were made (`handcheck`); None if not recorded."""
    sections: dict[str, Section] = field(default_factory=dict)
    """The Act's sections, for `verify.ending`; with none, the stops-early line is left out."""


