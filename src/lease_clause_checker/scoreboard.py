def _quotes_verified(run: ModelRun) -> int:
    return sum(_final_verified(result) for result in run.results)


def _final_verified(result: Result) -> bool:
    return not result.gave_up and result.attempts[-1].check == "verified"


def _light_right_heavy_wrong(scored: ScoredSet) -> str:
    """Clauses where a light model has the verdict and an accepted section and its heavy
    sibling (same method) does not."""
    found, ids = [], set()
    for light, heavy in _pairs():
        for method in METHODS:
            if scored.missing(method, light) or scored.missing(method, heavy):
                continue
            light_by_id = {s.clause.id: s for s in scored.run(method, light).scores}
            for heavy_score in scored.run(method, heavy).scores:
                light_score = light_by_id[heavy_score.clause.id]
                if _all_right(light_score) and not _all_right(heavy_score):
                    ids.add(heavy_score.clause.id)
                    found.append(
                        f"{heavy_score.clause.id} ({method}: {heavy.name} "
                        f"{_citation(heavy_score.answer)}; {light.name} "
                        f"{_citation(light_score.answer)})"
                    )
    listing = "; ".join(found) if found else "none"
    contested = sorted(ids & _contested_ids())
    see_note = f" On {_and_list(contested)}, see the note on contested labels." if contested else ""
    return (
        "Main-set clauses where a light model had the verdict and an accepted section and its "
        f"heavy sibling, by the same method, did not: {listing}.{see_note}"
    )


def _no_answer(run: ModelRun) -> str:
    """ "; k gave no verdict" for answers with no readable verdict (see the output-cap note),
    so the verdict columns visibly add up."""
    missing = sum(s.answer.verdict is None for s in run.scores)
    return f"; {missing} gave no verdict" if missing else ""


def _citation(answer: Answer) -> str:
    if answer.verdict is None and answer.section is None:
        return "gave no answer"
    if answer.section is None:
        return "cited no section"
    return f"cited s. {answer.section}"


