def _thinking_note(scored: ScoredSet) -> list[str]:
    """Median billed output tokens per main-set baseline answer, and Gemini's thinking share."""
    parts, silent = [], []
    for spec in MODELS:
        if scored.missing("baseline", spec):
            continue
        records = scored.run("baseline", spec).records
        part = f"{spec.name} {statistics.median(r.output_tokens for r in records):,.0f}"
        if spec.provider == "google":
            thinking = [_thinking_tokens(r.raw) for r in records]
            part += f" (thinking {statistics.median(thinking):,.0f})"
            if not any(thinking):
                silent.append(spec.name)
        parts.append(part)
    if not parts:
        return []
    line = (
        "- **Thinking.** Every model runs at its provider's default thinking setting (for "
        "Claude, effort medium). Median billed output tokens per main-set baseline answer, "
        f"thinking included (Gemini reports its thinking share): {'; '.join(parts)}."
    )
    for name in silent:
        line += f" At its default, {name} did not think on any main-set baseline answer."
    return [line]


def _thinking_tokens(raw: dict[str, Any]) -> int:
    usage = raw.get("usage_metadata") or {}
    return int(usage.get("thoughts_token_count") or 0)


def _output_cap_note(board: Board) -> list[str]:
    """Every scored answer the output-token cap stopped, by set, model and method. For the
    pipeline only the final attempt counts: a capped first attempt that was retried is not
    the answer scored."""
    groups = []
    for set_name, scored in (("main set", board.main), ("stress set", board.stress)):
        for (method, key), run in scored.runs.items():
            final = (
                [result.attempts[-1].record for result in run.results]
                if method == "pipeline"
                else run.records
            )
            capped = sorted(r.clause_id for r in final if r.finish_reason in OUTPUT_CAP_REASONS)
            if capped:
                groups.append(f"{_spec(key).name}, {method}, {set_name}: {', '.join(capped)}")
    if not groups:
        return []
    return [
        f"- **Output cap.** These answers stopped at the {MAX_OUTPUT_TOKENS:,}-token output "
        "cap, which thinking counts against, and are scored as they stand: "
        f"{'; '.join(sorted(groups))}. A baseline answer cut off before its verdict counts as "
        "a wrong verdict; a pipeline answer cut off counts as unsure."
    ]


def _contested_labels_note(scored: ScoredSet) -> list[str]:
    by_id = {c.id: c for c in scored.clauses}
    present = [item for item in CONTESTED_LABELS if item.clause_id in by_id]
    if not present:
        return []
    ids = _and_list([item.clause_id for item in present])
    lines = [
        f"- **Contested labels.** Answers argue against the frozen labels of {ids}: a label is "
        "listed here when a model's baseline answer argues against it from the Act's own "
        "provisions. They are scored as frozen, since the labels were fixed before any model saw "
        f"the set; the answers are read in full in [verdict-misses.md]({VERDICT_MISSES})."
    ]
    for item in present:
        clause = by_id[item.clause_id]
        scores = [
            (f"{_spec(key).name} ({method})", s)
            for (method, key), run in scored.runs.items()
            for s in run.scores
            if s.clause.id == item.clause_id
        ]
        wrong = sorted(name for name, s in scores if s.outcome in WRONG_VERDICTS)
        accepted = "".join(f", with s. {other} also accepted" for other in clause.also_accept)
        label = "lawful" if clause.label == "allowed" else "void"
        line = (
            f"  - **{clause.id}** (“{clause.text}”) is labelled {label} under s. "
            f"{clause.section}{accepted}. {_argued(item, scored)} Wrong verdict in the tables: "
            f"{', '.join(wrong) or 'none'}."
        )
        cited = item.unaccepted_section
        if cited is not None:
            if cited in (clause.section, *clause.also_accept):
                raise ReportDataError(f"{clause.id} now accepts s. {cited}; update the note")
            citing = sorted(name for name, s in scores if s.answer.section == cited)
            line += (
                f" Also, {item.why_cited}, but a citation of s. {cited} counts as a wrong "
                f"section. Cited s. {cited}: {', '.join(citing) or 'none'}."
            )
        lines.append(line)
    return lines


def _argued(item: ContestedLabel, scored: ScoredSet) -> str:
    """ "<Model>'s baseline answer argued that …", checked against each saved answer."""
    names = []
    for key, excerpt in item.argued_by:
        spec = _spec(key)
        where = f"contested label {item.clause_id}, {spec.name}"
        if scored.missing("baseline", spec):
            raise ReportDataError(f"{where}: baseline {scored.missing('baseline', spec)}")
        run = scored.run("baseline", spec)
        score = _one((s for s in run.scores if s.clause.id == item.clause_id), where)
        if score.outcome not in WRONG_VERDICTS:
            raise ReportDataError(f"{where}: the baseline verdict is not wrong")
        record = _one((r for r in run.records if r.clause_id == item.clause_id), where)
        if _normalise(excerpt) not in _normalise(record.text):
            raise ReportDataError(f"{where}: not in the answer: {excerpt!r}")
        names.append(f"{spec.name}'s")
    answers = "answers" if len(names) > 1 else "answer"
    return f"{' and '.join(names)} baseline {answers} argued {item.argument}."


def _late_fee_note(scored: ScoredSet) -> list[str]:
    clause_id, section = LATE_FEE_NOTE
    clause = next((c for c in scored.clauses if c.id == clause_id), None)
    if clause is None:
        return []
    if clause.section != section:
        raise ReportDataError(f"{clause_id} is no longer decided by s. {section}")
    return [
        f"- **{clause_id}** (stress set: “{clause.text}”) is decided by s. {section}'s “a "
        "specific sum becomes due upon a default of the tenant in paying rent due”, "
        "independently of O. Reg. 516/06, which as far as we know permits charges for "
        "bounced (NSF) payments but not late fees."
    ]


def render_chart(scored: ScoredSet) -> str:
    """An SVG dot plot: verdicts right and exact deciding section, per model and method."""
    n = len(scored.clauses)
    panels = (("Verdicts right", _verdict_right), ("Exact deciding section", _exact))
    label_w, panel_w, gap, top, row_h = 150, 260, 40, 70, 44
    width = label_w + 2 * panel_w + gap + 20
    plot_bottom = top + row_h * len(MODELS)
    height = plot_bottom + 52
    title = f"Main test set, {n} clauses: counts with {PERCENT} bootstrap intervals"
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" aria-labelledby="title desc" '
        'font-family="system-ui, sans-serif" font-size="12">',
        f'<title id="title">{title}</title>',
        '<desc id="desc">For each model, the number of clauses with the right verdict and with '
        "the exact deciding section, by the baseline (circles) and the pipeline (diamonds). "
        "The README's tables give the same numbers.</desc>",
        "<style>",
        ".bg{fill:#fcfcfb}.t1{fill:#0b0b0b}.t2{fill:#52514e}.grid{stroke:#e4e3df}"
        ".baseline{fill:#2a78d6;stroke:#2a78d6}.pipeline{fill:#eb6834;stroke:#eb6834}"
        ".ring{stroke:#fcfcfb}",
        "@media (prefers-color-scheme: dark){.bg{fill:#1a1a19}.t1{fill:#f0efec}"
        ".t2{fill:#c3c2b7}.grid{stroke:#3a3a38}.baseline{fill:#3987e5;stroke:#3987e5}"
        ".pipeline{fill:#d95926;stroke:#d95926}.ring{stroke:#1a1a19}}",
        "</style>",
        f'<rect class="bg" width="{width}" height="{height}"/>',
        f'<text class="t1" x="4" y="18" font-size="14" font-weight="600">{title}</text>',
        _legend_item(4, 40, "baseline", "baseline (plain question)"),
        _legend_item(204, 40, "pipeline", "pipeline (Act in prompt, checked quote)"),
    ]
    for p, (panel_title, test) in enumerate(panels):
        x0 = label_w + p * (panel_w + gap)

        def x(count: int, x0: int = x0) -> float:
            return x0 + panel_w * count / n

        out += [
            f'<text class="t1" x="{x0}" y="{top - 8}" font-weight="600">{panel_title}</text>',
            f'<text class="t2" x="{x0 + panel_w / 2:.1f}" y="{plot_bottom + 34}" '
            f'text-anchor="middle">clauses, of {n}</text>',
        ]
        for tick in sorted({0, 10, 20, 30, n}):
            out += [
                f'<line class="grid" x1="{x(tick):.1f}" x2="{x(tick):.1f}" y1="{top}" '
                f'y2="{plot_bottom}"/>',
                f'<text class="t2" x="{x(tick):.1f}" y="{plot_bottom + 16}" '
                f'text-anchor="middle">{tick}</text>',
            ]
        for r, spec in enumerate(MODELS):
            y_mid = top + row_h * r + row_h / 2
            if p == 0:
                out.append(f'<text class="t1" x="4" y="{y_mid + 4:.1f}">{spec.name}</text>')
            for m, method in enumerate(METHODS):
                y = y_mid + (m - 0.5) * 14
                missing = scored.missing(method, spec)
                if missing:
                    out.append(
                        f'<text class="t2" x="{x0}" y="{y + 4:.1f}">{method}: {missing}</text>'
                    )
                    continue
                hits = _hits(scored.run(method, spec), scored.clauses, test)
                low, high = count_interval(hits)
                tip = html.escape(f"{spec.name}, {method}: {sum(hits)} of {n} ({low}{DASH}{high})")
                out += [
                    f"<g><title>{tip}</title>",
                    f'<line class="{method}" x1="{x(low):.1f}" x2="{x(high):.1f}" '
                    f'y1="{y:.1f}" y2="{y:.1f}" stroke-width="2"/>',
                    _marker(method, x(sum(hits)), y),
                    "</g>",
                ]
    out.append("</svg>")
    return "\n".join(out) + "\n"


def _marker(method: Method, x: float, y: float) -> str:
    """A circle for the baseline, a diamond for the pipeline: shape as well as colour."""
    if method == "baseline":
        return (
            f'<circle class="{method} ring" cx="{x:.1f}" cy="{y:.1f}" r="5" stroke-width="2" '
            'paint-order="stroke"/>'
        )
    points = f"{x:.1f},{y - 6:.1f} {x + 6:.1f},{y:.1f} {x:.1f},{y + 6:.1f} {x - 6:.1f},{y:.1f}"
    return (
        f'<polygon class="{method} ring" points="{points}" stroke-width="2" paint-order="stroke"/>'
    )


def _legend_item(x: int, y: int, method: Method, label: str) -> str:
    return f'{_marker(method, x + 6, y - 4)}<text class="t2" x="{x + 18}" y="{y}">{label}</text>'
