"""The README's results: tables, a chart and a failure gallery, regenerated from saved answers.

`lcc report` (or `make report`) scores every saved answer, without calling any API, and
rewrites the block between `START` and `END` in README.md and the chart it links to. Every
number in the block comes from this module. Where the block describes a particular answer (the
gallery, the retry, the notes), the description is checked against the saved answer, and the
report stops with `ReportDataError` if they disagree.
"""

