def _stress_row(run: ModelRun, method: Method, label: str, n: int) -> str:
    wrong = sum(s.outcome in ("false_alarm", "missed_void", "no_verdict") for s in run.scores)
    unsure = sum(s.outcome == "unsure" for s in run.scores)
    section_only = sum(_verdict_right(s) and not _section_ok(s) for s in run.scores)
    right = sum(_all_right(s) for s in run.scores)
    return (
        f"| {run.spec.name} ({run.spec.weight}) | {method} | {label} | {wrong} of {n} "
        f"| {unsure if method == 'pipeline' else DASH} | {section_only} of {n} "
        f"| {right} of {n} | {_cost(run)} |"
    )


